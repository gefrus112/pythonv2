/* Games page: tabs, PyHope Comet Hopper, CPU arena, and 9M GPU demo. */
(function () {
  "use strict";

  // ------------------------------------------------------------------
  // Accessible page tabs
  // ------------------------------------------------------------------
  const tabs = [...document.querySelectorAll("[data-game-tab]")];
  const panels = [...document.querySelectorAll("[data-game-panel]")];
  function selectTab(name) {
    tabs.forEach((button) => {
      const on = button.dataset.gameTab === name;
      button.setAttribute("aria-selected", on ? "true" : "false");
      button.tabIndex = on ? 0 : -1;
    });
    panels.forEach((panel) => { panel.hidden = panel.dataset.gamePanel !== name; });
    if (history.replaceState) history.replaceState(null, "", "#" + name);
  }
  tabs.forEach((button, index) => {
    button.addEventListener("click", () => selectTab(button.dataset.gameTab));
    button.addEventListener("keydown", (event) => {
      if (!['ArrowLeft', 'ArrowRight'].includes(event.key)) return;
      event.preventDefault();
      const step = event.key === 'ArrowRight' ? 1 : -1;
      const next = tabs[(index + step + tabs.length) % tabs.length];
      selectTab(next.dataset.gameTab);
      next.focus();
    });
  });
  const initialTab = location.hash.slice(1);
  selectTab(tabs.some((tab) => tab.dataset.gameTab === initialTab) ? initialTab : "play");

  // ------------------------------------------------------------------
  // CPU monster arena
  // ------------------------------------------------------------------
  const arenaCanvas = document.getElementById("arena-canvas");
  if (arenaCanvas && typeof CpuGame !== "undefined") {
    const arena = new CpuGame(arenaCanvas, {
      fps: document.getElementById("arena-fps"),
      pos: document.getElementById("arena-pos"),
      kills: document.getElementById("arena-kills"),
      pixels: document.getElementById("arena-pixels"),
    });
    arena.attach();
    arena.start();
  }

  // ------------------------------------------------------------------
  // GPU raycaster (opt-in high-resolution mode)
  // ------------------------------------------------------------------
  const gpuCanvas = document.getElementById("gpu-canvas");
  let gpu = null;
  if (gpuCanvas && typeof GpuRaycaster !== "undefined") {
    gpu = new GpuRaycaster(gpuCanvas, { status: document.getElementById("gpu-status") });
    gpu.attach();
  }
  const gpuLive = document.getElementById("gpu-live");
  const gpu9m = document.getElementById("gpu-9m");
  if (gpuLive) gpuLive.addEventListener("click", () => gpu && gpu.start());
  if (gpu9m) gpu9m.addEventListener("click", () => gpu && gpu.renderNineMillion());

  // ------------------------------------------------------------------
  // Comet Hopper — original side-scrolling platform game.
  // The level rows are generated by Python v2 running in the browser.
  // ------------------------------------------------------------------
  function CometHopper(canvas, status) {
    this.canvas = canvas;
    this.ctx = canvas.getContext("2d");
    this.status = status;
    this.width = 640;
    this.height = 360;
    canvas.width = this.width;
    canvas.height = this.height;
    this.tile = 32;
    this.keys = new Set();
    this.hero = { x: 64, y: 100, vx: 0, vy: 0, w: 25, h: 29, grounded: false };
    this.camera = 0;
    this.coins = [];
    this.enemies = [];
    this.score = 0;
    this.won = false;
    this.last = performance.now();
    this.images = {};
    this.level = this.loadLevel();
    this.loadImages();
    this.bind();
  }

  CometHopper.prototype.loadLevel = function () {
    const fallback = [
      "................................................................",
      "................................................................",
      "..............................................................F.",
      "...........................C..................................###",
      ".............C...........####...........C.......................",
      ".........#####........................#####.............C........",
      "..C..................M................................####.......",
      "#####...........########...........M.........................####",
      ".....####........................####...........#####.............",
      "..........C.........C............................................",
      "################################################################",
    ];
    const script = document.getElementById("platform-level");
    if (!script || typeof Pyv2 === "undefined") return fallback;
    const result = Pyv2.runCapture(script.textContent);
    if (result.error) {
      if (this.status) this.status.textContent = "Level script error: " + result.error;
      return fallback;
    }
    const rows = result.output.split("\n").filter(Boolean);
    return rows.length >= 5 ? rows : fallback;
  };

  CometHopper.prototype.loadImages = function () {
    const files = {
      hero: "assets/sprites/comet-hero.svg",
      enemy: "assets/sprites/slime.svg",
      coin: "assets/sprites/coin.svg",
    };
    Object.entries(files).forEach(([name, src]) => {
      const image = new Image();
      image.src = src;
      this.images[name] = image;
    });
  };

  CometHopper.prototype.bind = function () {
    for (let y = 0; y < this.level.length; y++) {
      for (let x = 0; x < this.level[y].length; x++) {
        const tile = this.level[y][x];
        if (tile === "C") this.coins.push({ x: x * this.tile + 8, y: y * this.tile + 8, taken: false });
        if (tile === "M") this.enemies.push({ x: x * this.tile + 3, y: y * this.tile + 5, vx: -40, alive: true });
      }
    }
    this._down = (event) => {
      this.keys.add(event.code);
      if (["ArrowLeft", "ArrowRight", "ArrowUp", "Space"].includes(event.code) && document.activeElement === this.canvas) {
        event.preventDefault();
      }
    };
    this._up = (event) => this.keys.delete(event.code);
    window.addEventListener("keydown", this._down);
    window.addEventListener("keyup", this._up);
    this.canvas.addEventListener("click", () => this.canvas.focus());
    this.canvas.tabIndex = 0;
  };

  CometHopper.prototype.solid = function (px, py) {
    const x = Math.floor(px / this.tile), y = Math.floor(py / this.tile);
    if (y < 0 || y >= this.level.length || x < 0 || x >= this.level[y].length) return y >= this.level.length || x < 0;
    return this.level[y][x] === "#";
  };

  CometHopper.prototype.reset = function () {
    Object.assign(this.hero, { x: 64, y: 100, vx: 0, vy: 0 });
    this.camera = 0;
    this.score = 0;
    this.won = false;
    this.coins.forEach((coin) => { coin.taken = false; });
    this.enemies.forEach((enemy) => { enemy.alive = true; });
  };

  CometHopper.prototype.moveAxis = function (axis, amount) {
    const hero = this.hero;
    hero[axis] += amount;
    const left = hero.x + 3, right = hero.x + hero.w - 3;
    const top = hero.y + 2, bottom = hero.y + hero.h;
    if (axis === "x") {
      if (amount > 0 && (this.solid(right, top) || this.solid(right, bottom - 2))) {
        hero.x = Math.floor(right / this.tile) * this.tile - hero.w - 0.01;
        hero.vx = 0;
      } else if (amount < 0 && (this.solid(left, top) || this.solid(left, bottom - 2))) {
        hero.x = (Math.floor(left / this.tile) + 1) * this.tile - 3;
        hero.vx = 0;
      }
    } else {
      hero.grounded = false;
      if (amount > 0 && (this.solid(left, bottom) || this.solid(right, bottom))) {
        hero.y = Math.floor(bottom / this.tile) * this.tile - hero.h - 0.01;
        hero.vy = 0;
        hero.grounded = true;
      } else if (amount < 0 && (this.solid(left, top) || this.solid(right, top))) {
        hero.y = (Math.floor(top / this.tile) + 1) * this.tile - 2;
        hero.vy = 0;
      }
    }
  };

  CometHopper.prototype.update = function (dt) {
    const hero = this.hero;
    const left = this.keys.has("ArrowLeft") || this.keys.has("KeyA");
    const right = this.keys.has("ArrowRight") || this.keys.has("KeyD");
    hero.vx += ((right ? 1 : 0) - (left ? 1 : 0)) * 900 * dt;
    hero.vx *= Math.pow(0.0008, dt);
    hero.vx = Math.max(-230, Math.min(230, hero.vx));
    if ((this.keys.has("ArrowUp") || this.keys.has("KeyW") || this.keys.has("Space")) && hero.grounded) {
      hero.vy = -430;
      hero.grounded = false;
    }
    hero.vy = Math.min(700, hero.vy + 1050 * dt);
    this.moveAxis("x", hero.vx * dt);
    this.moveAxis("y", hero.vy * dt);
    if (hero.y > this.height + 80) this.reset();

    for (const coin of this.coins) {
      if (!coin.taken && Math.abs(hero.x - coin.x) < 25 && Math.abs(hero.y - coin.y) < 30) {
        coin.taken = true;
        this.score++;
      }
    }
    for (const enemy of this.enemies) {
      if (!enemy.alive) continue;
      enemy.x += enemy.vx * dt;
      const ahead = enemy.x + (enemy.vx > 0 ? 30 : -2);
      if (this.solid(ahead, enemy.y + 15) || !this.solid(ahead, enemy.y + 34)) enemy.vx *= -1;
      if (Math.abs(hero.x - enemy.x) < 25 && Math.abs(hero.y - enemy.y) < 26) {
        if (hero.vy > 80 && hero.y < enemy.y - 5) {
          enemy.alive = false;
          hero.vy = -260;
          this.score += 3;
        } else this.reset();
      }
    }
    const finishX = (this.level[0].length - 3) * this.tile;
    if (hero.x > finishX) this.won = true;
    this.camera += ((hero.x - 180) - this.camera) * Math.min(1, dt * 5);
    this.camera = Math.max(0, Math.min(this.level[0].length * this.tile - this.width, this.camera));
    if (this.status) this.status.textContent = this.won ? "LEVEL CLEAR! • Hope Bits " + this.score : "HOPE BITS " + this.score + " • level generated by Python v2";
  };

  CometHopper.prototype.draw = function () {
    const ctx = this.ctx, tile = this.tile;
    const sky = ctx.createLinearGradient(0, 0, 0, this.height);
    sky.addColorStop(0, "#12243c");
    sky.addColorStop(0.68, "#3d6b96");
    sky.addColorStop(1, "#ffcf77");
    ctx.fillStyle = sky;
    ctx.fillRect(0, 0, this.width, this.height);
    // distant pixel mountains
    ctx.fillStyle = "rgba(20,42,66,.6)";
    for (let x = -80; x < this.width + 100; x += 110) {
      const px = x - (this.camera * 0.18 % 110);
      ctx.beginPath(); ctx.moveTo(px, 310); ctx.lineTo(px + 58, 185); ctx.lineTo(px + 120, 310); ctx.fill();
    }

    const startX = Math.max(0, Math.floor(this.camera / tile) - 1);
    const endX = Math.min(this.level[0].length, startX + Math.ceil(this.width / tile) + 3);
    for (let y = 0; y < this.level.length; y++) {
      for (let x = startX; x < endX; x++) {
        const cell = this.level[y][x];
        const dx = x * tile - this.camera, dy = y * tile;
        if (cell === "#") {
          ctx.fillStyle = "#1e2f3d"; ctx.fillRect(dx, dy, tile, tile);
          ctx.fillStyle = "#2f6fbd"; ctx.fillRect(dx + 2, dy + 2, tile - 4, 7);
          ctx.fillStyle = "#5fc4dc"; ctx.fillRect(dx + 3, dy + 3, tile - 6, 2);
        } else if (cell === "F") {
          ctx.fillStyle = "#ffd343"; ctx.fillRect(dx + 14, dy - 24, 3, 56);
          ctx.fillStyle = "#d64541"; ctx.fillRect(dx + 17, dy - 22, 24, 15);
        }
      }
    }

    for (const coin of this.coins) {
      if (coin.taken) continue;
      const x = coin.x - this.camera, y = coin.y + Math.sin(performance.now() / 180 + coin.x) * 3;
      if (this.images.coin.complete) ctx.drawImage(this.images.coin, x, y, 24, 24);
      else { ctx.fillStyle = "#ffd343"; ctx.fillRect(x + 5, y, 12, 24); }
    }
    for (const enemy of this.enemies) {
      if (!enemy.alive) continue;
      const x = enemy.x - this.camera;
      if (this.images.enemy.complete) ctx.drawImage(this.images.enemy, x, enemy.y, 30, 30);
      else { ctx.fillStyle = "#44a36f"; ctx.fillRect(x, enemy.y, 28, 28); }
    }
    const hx = this.hero.x - this.camera;
    if (this.images.hero.complete) ctx.drawImage(this.images.hero, hx, this.hero.y, this.hero.w, this.hero.h);
    else { ctx.fillStyle = "#d64541"; ctx.fillRect(hx, this.hero.y, this.hero.w, this.hero.h); }

    if (this.won) {
      ctx.fillStyle = "rgba(16,28,40,.86)"; ctx.fillRect(125, 115, 390, 120);
      ctx.fillStyle = "#ffd343"; ctx.font = "bold 32px sans-serif"; ctx.textAlign = "center";
      ctx.fillText("LEVEL CLEAR!", 320, 165);
      ctx.fillStyle = "#fff"; ctx.font = "18px sans-serif";
      ctx.fillText("Press R to run it again", 320, 202); ctx.textAlign = "left";
      if (this.keys.has("KeyR")) this.reset();
    }
  };

  CometHopper.prototype.start = function () {
    const loop = (time) => {
      const dt = Math.min(0.05, (time - this.last) / 1000);
      this.last = time;
      this.update(dt);
      this.draw();
      requestAnimationFrame(loop);
    };
    requestAnimationFrame(loop);
  };

  const platformCanvas = document.getElementById("platform-canvas");
  if (platformCanvas) {
    const platformer = new CometHopper(platformCanvas, document.getElementById("platform-status"));
    platformer.start();
    const reset = document.getElementById("platform-reset");
    if (reset) reset.addEventListener("click", () => platformer.reset());
  }
})();
